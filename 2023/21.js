function markStart(g) {
    let gg = g.copy()
    let startI, startJ

    // find start
    for (let [i, j] of g.indexes()) {
        if (g[i][j] == 'S') {
            startI = i
            startJ = j
            break
        }
    }

    gg[startI][startJ] = 'O'

    return gg
}

function step(g) {
    let gg = g.copy()
    for (let [i, j] of g.indexes()) {
        if (g[i][j] == 'O') {
            for (let [ii, jj] of g.neighbors(i, j, false)) {
                if (g[ii][jj] != '#') {
                    gg[ii][jj] = 'O'
                }
            }
            gg[i][j] = '.'
        }
    }
    return gg
}

function partA(g, limit) {
    g = markStart(g)

    for (let k=0; k<limit; k++) {
        g = step(g)
    }

    g.print()

    let count = 0
    for (let [i, j] of g.indexes()) {
        if (g[i][j] == 'O') {
            count++
        }
    }
    return count
}

function expandGrid(g, n) {
    let h = g.h()
    let w = g.w()
    let gg = u.newGrid(h*n, w*n)

    for (let [i, j] of g.indexes()) {
        for (let k=0; k < n; k++) {
            for (let l=0; l < n; l++) {
                gg[i+k*h][j+l*w] = !(k == (n-1)/2 && l == (n-1)/2) && g[i][j] == 'S' ? '.' : g[i][j]
            }
        }
    }

    return gg
}

function countQuadrant(g, num, i, j) {
    let h = g.h() / num
    let w = g.w() / num

    let sum = 0
    for (let ii=0; ii < h; ii++) {
        for (let jj=0; jj < w; jj++) {
            if (g[ii + i*h][jj + j*w] == 'O') sum++
        }
    }
    return sum
}

function countZeros(a) {
    for (let i=0; i < a.length; i++) {
        if (a[i] != 0) return i
    }
    return a.length
}

function stripZeros(a) {
    let aa = []
    let foundZero = false
    for (let i=0; i < a.length; i++) {
        if (a[i] != 0) foundZero = true
        if (foundZero) aa.push(a[i])
    }
    return aa
}

